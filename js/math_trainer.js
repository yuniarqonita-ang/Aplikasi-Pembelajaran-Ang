    /**
     * Standard normalization for mathematical user input:
     * - Strips surrounding spaces, lowercase
     * - Handles spaces around math symbols (e.g. '3 / 4' -> '3/4', 'x = 5' -> 'x=5')
     * - Strips units like cm, cm2, m, derajat, °, satuan, dsb
     * - Normalizes decimal comma (0,5 -> 0.5)
     */
    window.normalizeMathAnswer = function(str) {
        if (str === null || str === undefined) return '';
        var s = String(str).trim().toLowerCase();
        // Replace unicode degree or pi symbols if needed
        s = s.replace(/[°]/g, '°');
        // Replace comma as decimal if followed by digit
        s = s.replace(/(\d+),(\d+)/g, '$1.$2');
        // Strip common unit suffixes
        s = s.replace(/\s*(cm\^2|cm2|cm|meter|m|derajat|deg|buah|bilangan|satuan|unit|persamaan|suku)/gi, '');
        // Collapse spaces
        s = s.replace(/\s+/g, ' ').trim();
        return s;
    };

    /**
     * Evaluates user input against expected answer and accepted variations.
     * Supports fractional equivalence, numeric float tolerance (+-0.05), and algebraic strings.
     */
    window.checkMathChallengeAnswer = function(challengeId, userInput) {
        var all = window.getAllMathChallenges();
        var item = all.find(function(c) { return c.id === challengeId; });
        if (!item) {
            return {
                isCorrect: false,
                feedback: 'Soal tidak ditemukan.',
                explanation: ''
            };
        }

        var cleanedInput = window.normalizeMathAnswer(userInput);
        var expectedClean = window.normalizeMathAnswer(item.expectedAnswer);

        if (!cleanedInput) {
            return {
                isCorrect: false,
                feedback: 'Silakan ketik atau gunakan tombol keypad matematika untuk mengisi jawabanmu!',
                explanation: ''
            };
        }

        // Direct match with expected
        if (cleanedInput === expectedClean) {
            return {
                isCorrect: true,
                feedback: 'Luar biasa! Jawabanmu tepat dan sesuai standar Cambridge!',
                explanation: item.explanation
            };
        }

        // Check accepted answers list
        var accepted = (item.acceptedAnswers || []).map(function(ans) {
            return window.normalizeMathAnswer(ans);
        });

        for (var i = 0; i < accepted.length; i++) {
            if (cleanedInput === accepted[i]) {
                return {
                    isCorrect: true,
                    feedback: 'Tepat sekali! Bentuk penyederhanaan jawabanmu benar!',
                    explanation: item.explanation
                };
            }
        }

        // Check if both are numeric (float comparison with tolerance 0.05)
        var numUser = parseFloat(cleanedInput);
        var numExp = parseFloat(expectedClean);
        if (!isNaN(numUser) && !isNaN(numExp) && isFinite(numUser) && isFinite(numExp)) {
            // Also check if expected had a fraction like "3/4"
            if (expectedClean.indexOf('/') !== -1) {
                var parts = expectedClean.split('/');
                if (parts.length === 2) {
                    var n = parseFloat(parts[0]);
                    var d = parseFloat(parts[1]);
                    if (d !== 0) numExp = n / d;
                }
            }
            if (cleanedInput.indexOf('/') !== -1) {
                var uParts = cleanedInput.split('/');
                if (uParts.length === 2) {
                    var un = parseFloat(uParts[0]);
                    var ud = parseFloat(uParts[1]);
                    if (ud !== 0) numUser = un / ud;
                }
            }
            if (Math.abs(numUser - numExp) < 0.05) {
                return {
                    isCorrect: true,
                    feedback: 'Benar! Nilai kalkulasi matematis sesuai!',
                    explanation: item.explanation
                };
            }
        }

        // Compact match (ignoring all spaces e.g., "(x + 3)(x + 5)" vs "(x+3)(x+5)")
        var compactUser = cleanedInput.replace(/\s+/g, '');
        var compactExpected = expectedClean.replace(/\s+/g, '');
        if (compactUser === compactExpected) {
            return {
                isCorrect: true,
                feedback: 'Bagus! Notasi aljabarmu benar!',
                explanation: item.explanation
            };
        }

        for (var j = 0; j < accepted.length; j++) {
            var compactAcc = accepted[j].replace(/\s+/g, '');
            if (compactUser === compactAcc) {
                return {
                    isCorrect: true,
                    feedback: 'Bagus! Notasi aljabarmu benar!',
                    explanation: item.explanation
                };
            }
        }

        // Incorrect feedback with pedagogical guidance (no spoilers)
        return {
            isCorrect: false,
            feedback: 'Jawabanmu belum tepat. Yuk cek petunjuk logika Kodi di bawah dan hitung kembali!',
            hint: item.hint,
            explanation: ''
        };
    };

